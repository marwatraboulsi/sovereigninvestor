export function searchTickers(query: string, limit = 8): TickerInfo[] {
  if (!query.trim()) return [];
  const q = query.toUpperCase().trim();
  const exact: TickerInfo[] = [];
  const startsWith: TickerInfo[] = [];
  const nameMatch: TickerInfo[] = [];

  for (const t of TICKERS) {
    if (t.ticker === q) exact.push(t);
    else if (t.ticker.startsWith(q)) startsWith.push(t);
    else if (t.name.toUpperCase().includes(q)) nameMatch.push(t);
  }

  return [...exact, ...startsWith, ...nameMatch].slice(0, limit);
}
